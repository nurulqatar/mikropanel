function normalizeLocale(
    locale = 'en',
) {
    return String(locale)
        .toLowerCase()
        .replace('_', '-');
}

export function createTranslator(
    locale = 'en',
    customTranslations = {},
) {
    const normalized =
        normalizeLocale(locale);

    const base =
        normalized.split('-')[0];

    const builtIn =
        translations[normalized]
        || translations[base]
        || en;

    const custom =
        customTranslations?.[normalized]
        || customTranslations?.[base]
        || {};

    return (key) =>
        custom?.[key]
        ?? builtIn?.[key]
        ?? en[key]
        ?? key;
}

export function hasBuiltInTranslation(
    locale,
) {
    const normalized =
        normalizeLocale(locale);

    return Boolean(
        translations[normalized]
        || translations[
            normalized.split('-')[0]
        ],
    );
}
